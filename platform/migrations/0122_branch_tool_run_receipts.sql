CREATE TABLE IF NOT EXISTS branch_tool_run_receipts (
    receipt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL,
    subject text NOT NULL,
    idempotency_key text NOT NULL CHECK (idempotency_key ~ '^[0-9a-f]{32}$'),
    request_sha256 text NOT NULL,
    name text NOT NULL,
    version text NOT NULL,
    package_digest text NOT NULL,
    kind text NOT NULL CHECK (kind IN ('arrived', 'verify_failed', 'ran')),
    outcome text CHECK (outcome IN ('ok', 'failed', 'cancelled')),
    plugin_version text NOT NULL,
    duration_ms integer CHECK (duration_ms BETWEEN 0 AND 600000),
    drawing_line text CHECK (char_length(drawing_line) <= 1024),
    error_code text CHECK (char_length(error_code) <= 64),
    error_message text CHECK (char_length(error_message) <= 300),
    occurred_at timestamptz,
    received_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (tenant_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS branch_tool_run_receipts_package_idx
    ON branch_tool_run_receipts (tenant_id, name, version, receipt_id DESC);
CREATE INDEX IF NOT EXISTS branch_tool_run_receipts_age_idx
    ON branch_tool_run_receipts (tenant_id, received_at);
