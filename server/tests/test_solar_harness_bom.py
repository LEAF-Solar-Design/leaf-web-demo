def test_generate_pile_coordinates_samples_the_terrain_at_each_pile():
    """The plugin's case uses TerrainGridInterpolator, which this slice does not
    port; the sampling CONTRACT is what the exporter owns, so it is a double."""
    sampled = []

    class Terrain:
        def interpolate_z(self, x, y):
            sampled.append((x, y))
            return 150.0

    rows = [engine.TrackerRow(row_index=0, module_slots=10, length_meters=10,
                              rail_overhang_m=0.0, axis_start=(5, 0), axis_end=(5, 10))]
    piles = engine.generate_pile_coordinates(rows, 5.0, Terrain())
    assert all(pile.terrain_z == pytest.approx(150.0, abs=1e-6) for pile in piles)
    assert sampled == [(pile.x, pile.y) for pile in piles]


