def test_aggregate_quantises_to_one_millimetre():
    """Drops a micron apart are ONE bucket; a millimetre apart are two."""
    def harness(*drops):
        return engine.HarnessSpec(type=engine.END_OF_ROW, connectors=len(drops),
                                  cable_gauge_awg=10, module_drop_lengths_m=drops,
                                  total_cable_length_m=sum(drops))
    summaries = engine.aggregate_harness_extensions(
        [harness(1.0, 1.0000004), harness(1.001)])
    assert [(entry.drop_length_m, entry.count) for entry in summaries] == [(1.0, 2), (1.001, 1)]


