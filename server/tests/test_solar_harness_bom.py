def generated_workbook(name):
    """Studio's workbook through its own writer and reader, so both sides are
    compared as the cell values rule E5 names, never as storage bytes."""
    return xlsx.read_workbook(xlsx.write_workbook(generated(name)))


def rows_of(sheets, name):
    for sheet in sheets:
        if sheet.name == name:
            return {row.index: row.cells for row in sheet.rows}
    raise AssertionError("workbook has no sheet " + name)


def csv_rows(text):
    """The capture's data rows as dicts, keyed by the pipe-separated header."""
    lines = [line for line in text.replace("\r\n", "\n").split("\n") if line]
    header = lines[0].split("|")
    return {cells[0]: dict(zip(header, cells))
            for cells in (line.split("|") for line in lines[1:])}


