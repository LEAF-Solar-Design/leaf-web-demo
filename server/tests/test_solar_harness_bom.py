"""Studio's harness planner and tracker BOM against the licensed plugin, computed.

Three layers, all hermetic and none of them skipping:

  1. The plugin's OWN unit tests, ported case for case from
     Tests/Tests/LeafHarnessCalculatorTests.cs, Tests/Tests/LeafBomTests.cs,
     Tests/Tests/LeafBomXlsxTests.cs and Tests/Tests/LeafBomXlsxHarnessTests.cs
     (read 2026-09-22 at C:/tmp/solar-parity/wt-b25-s17). The two
     `GetActiveModule` cases are omitted: they read AutoCAD drawing properties,
     which is not what this port covers, and the omission is named here rather
     than left as a silent gap.
  2. Every probe in the four licensed DEMO captures, reproduced by RUNNING
     Studio's fixtures through server/solar_harness_bom.py. The captures are the
     licensed AutoCAD 2025 run of 2026-09-23 and are COMMITTED at
     docs/parity/evidence/probes/demo-probes-20260923, so this layer reads the
     artifact itself rather than a transcription and every runner carries it.
     Each file is asserted whole and then probe by probe, so a failure names the
     scenario or the sheet row that moved.
  3. The branches the EMPTY demo exists to pin: Cable Tray null versus empty,
     the Electrical and Piling placeholders, and the By Area first-occurrence
     grouping.

Line endings, and why the whole-file assertion normalizes them. The plugin
writes CRLF and this port writes CRLF, which `test_the_generated_csv_uses_the
_plugins_crlf_and_ascii` asserts on the GENERATED bytes. The committed capture
is a tracked text file, so git's checkout translation decides its on-disk line
endings, and comparing against it byte for byte would be asserting a git setting
rather than a parity fact. The workbooks are binary to git and are compared as
cell values, which is what rule E5 compares.

Nothing here feeds a captured value back into the port: solar_harness_bom.py
computes every number and renders every string, and these are the assertions it
must meet.
"""

