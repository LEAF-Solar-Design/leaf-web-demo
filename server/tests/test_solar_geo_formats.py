LICENSED_KML_PATH = r"C:\Users\User\AppData\Local\Temp\leafkmlexport_demo.kml"
CSV_FILES = ("leafkmlexportfmt_demo.csv", "leafkmlimport_demo.csv", "leafimportlandxml_demo.csv")


@functools.lru_cache(maxsize=None)
def generated_bytes(name):
    """Studio's own bytes for one file, computed from its fixture (once per run)."""
    demo = probes.FILE_DEMOS[name]
    if demo == "leafkmlimport":
        files = probes.build_kml_import(kml_path=LICENSED_KML_PATH)
    else:
        files = probes.build(demo)
    return probes.file_bytes(name, files[name])


def reference_bytes(name):
    return (REFERENCE_DIR / name).read_bytes()


def lf(data):
    return data.replace(b"\r\n", b"\n")


def data_rows(data):
    """(header cells, [row cells]) of one probe CSV: BOM and `#` preamble skipped."""
    text = data.decode("utf-8")
    if text.startswith("\ufeff"):
        text = text[1:]
    lines = [line for line in text.replace("\r\n", "\n").split("\n") if line]
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return lines[0].split(","), [line.split(",") for line in lines[1:]]


def _licensed_row_cases():
    cases = []
    for name in CSV_FILES:
        _, rows = data_rows(reference_bytes(name))
        cases.extend((name, index) for index in range(len(rows)))
    return cases


