def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


engine = _load("solar_geo_formats", ROOT / "server" / "solar_geo_formats.py")
probes = _load("solar_geo_formats_probes", ROOT / "scripts" / "solar_geo_formats_probes.py")

REFERENCE_DIR = ROOT / "docs/parity/evidence/probes/demo-probes-20260923"
ALL_FILES = tuple(name for demo in sorted(probes.DEMOS) for name in probes.file_names(demo))
BOM = b"\xef\xbb\xbf"
# The commands that pass Encoding.UTF8 to File.WriteAllText.
FILES_WITH_BOM = frozenset({"leafkmlimport_demo.csv", "leaflandxml_fixed.xml",
                            "leaflandxml_delaunay.xml"})
# XmlWriter writes no newline after the root's end tag; AppendLine always does.
FILES_WITHOUT_FINAL_NEWLINE = frozenset(
    name for name in ALL_FILES if name.endswith(".kml") or name.startswith("leafkmlexportfmt_demo_F"))
# The file LEAFKMLIMPORTDEMO read on the licensed host; it appears only in the
