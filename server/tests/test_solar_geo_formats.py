"""Studio's KML and LandXML writers and readers against the licensed plugin, computed.

Three layers, all hermetic and none of them skipping:

  1. Every file the five licensed DEMOs wrote (LEAFKMLEXPORTDEMO,
     LEAFKMLEXPORTFMTDEMO, LEAFKMLIMPORTDEMO, LEAFLANDXMLDEMO and
     LEAFIMPORTLANDXMLDEMO), reproduced by RUNNING Studio's fixtures through
     server/solar_geo_formats.py. The captures are the licensed AutoCAD 2025 run
     of 2026-09-23 and are COMMITTED at
     docs/parity/evidence/probes/demo-probes-20260923, so this layer reads the
     artifact itself. Each file is asserted whole, and each CSV row by row (one
     test per licensed row, collected from the committed file), so a failure
     names the row.
  2. The format branches the plugin's writers and readers take, one behaviour
     per test: altitude omission, ring closure and its epsilon, missing names,
     null polygons, G17, escaping, the pole guard, namespace stripping, the
     silent skip of malformed LandXML points, the Delaunay in-circle test, and
     the IDW resampler.
  3. Hostile XML: a DOCTYPE, internal and external entities, parameter
     entities, an undefined entity, unbound prefixes, depth and size bounds.
     Every XML entry point refuses them before any expansion can happen.

Two inputs that are not geometry. The LandXML header carries DateTime.UtcNow,
which the scenario pins (solar_geo_formats_probes.LANDXML_UTC_NOW). The import
report's `#` line names the file the importer read, so the whole-file check
passes the path the licensed run read (LICENSED_KML_PATH); the rows below it
are asserted independently of that line.

Line endings. The plugin writes CRLF and this port writes CRLF, which
`test_generated_bytes_carry_the_plugins_encoding_and_crlf` asserts on the
GENERATED bytes. The committed capture is a tracked text file, so the whole-file
assertion normalizes CRLF to LF on both sides rather than asserting a git
setting. The byte order mark is not a line ending, so that assertion keeps it.

C# exception types map to Python ones: ArgumentNullException to TypeError,
ArgumentException to ValueError (KmlArgumentError for the pole guard),
XmlException and FormatException to GeoFormatError.
"""

