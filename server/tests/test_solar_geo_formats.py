@pytest.mark.parametrize("name", ALL_FILES)
def test_generated_bytes_carry_the_plugins_encoding_and_crlf(name):
    data = generated_bytes(name)
    assert data.startswith(BOM) == (name in FILES_WITH_BOM)
    assert b"\n" in data
    assert data.count(b"\n") == data.count(b"\r\n")
    assert data.endswith(b"\r\n") == (name not in FILES_WITHOUT_FINAL_NEWLINE)
    data.decode("utf-8")


@pytest.mark.parametrize("name,index", _licensed_row_cases())
def test_licensed_csv_row_is_reproduced(name, index):
    reference_header, reference_rows = data_rows(reference_bytes(name))
    header, rows = data_rows(generated_bytes(name))
    assert header == reference_header
    assert len(rows) == len(reference_rows)
    assert rows[index] == reference_rows[index]


