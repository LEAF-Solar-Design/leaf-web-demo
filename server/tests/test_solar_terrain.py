ROOT = Path(__file__).resolve().parents[2]


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


engine = _load("solar_terrain", ROOT / "server" / "solar_terrain.py")
probes = _load("solar_terrain_probes", ROOT / "scripts" / "solar_terrain_probes.py")

# The licensed capture is committed in this repo, so every runner carries it.
REFERENCE_DIR = ROOT / "docs/parity/evidence/probes/demo-probes-20260923"
ALL_FILES = tuple(name for demo in sorted(probes.DEMOS) for name in probes.file_names(demo))
BOM = b"\xef\xbb\xbf"
# Which files carry Encoding.UTF8's preamble: the four commands that pass it.
FILES_WITH_BOM = frozenset({"leafhorizon_demo.csv", "leafgradingpad_demo.csv",
                            "leafcrosssection_demo.csv", "leafcapacity_demo.csv"})


@functools.lru_cache(maxsize=None)
def generated_bytes(name):
    """Studio's own bytes for one file, computed from its fixture (once per run)."""
    content = probes.build(probes.FILE_DEMOS[name])[name]
    return probes.file_bytes(name, content)


def reference_bytes(name):
    return (REFERENCE_DIR / name).read_bytes()


def lf(data):
    return data.replace(b"\r\n", b"\n")


def data_rows(data):
    """(header cells, [row cells]) of one probe CSV: BOM and `#` preamble skipped."""
    text = data.decode("utf-8")
    if text.startswith("\ufeff"):
        text = text[1:]
    lines = [line for line in text.replace("\r\n", "\n").split("\n") if line]
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return lines[0].split(","), [line.split(",") for line in lines[1:]]


def _licensed_row_cases():
    """One (file, index) per licensed data row, read from the COMMITTED capture.

    Reading at collection means a missing capture is a collection error, never
    a skip, and a capture that gains or loses a row changes the case list.
    """
    cases = []
    for name in ALL_FILES:
        _, rows = data_rows(reference_bytes(name))
        cases.extend(pytest.param(name, index, id="%s:%d" % (name, index + 1))
                     for index in range(len(rows)))
    return cases


