@pytest.mark.parametrize("name", ALL_FILES)
def test_the_generated_file_is_the_licensed_capture(name):
    assert lf(generated_bytes(name)) == lf(reference_bytes(name))


@pytest.mark.parametrize("name", ALL_FILES)
def test_the_generated_bytes_carry_the_plugins_encoding_and_crlf(name):
    data = generated_bytes(name)
    assert data.startswith(BOM) == (name in FILES_WITH_BOM)
    assert reference_bytes(name).startswith(BOM) == (name in FILES_WITH_BOM)
    assert data.endswith(b"\r\n")
    assert b"\n" not in data.replace(b"\r\n", b"")
    assert b"\r" not in data.replace(b"\r\n", b"")
    assert b'"' not in data
    if name == "leafheatmap_demo.csv":
        data.decode("ascii")


@pytest.mark.parametrize("name,index", _licensed_row_cases())
def test_every_licensed_probe_is_reproduced(name, index):
    ref_header, ref_rows = data_rows(reference_bytes(name))
    gen_header, gen_rows = data_rows(generated_bytes(name))
    assert gen_header == ref_header
    assert len(gen_rows) == len(ref_rows)
    assert dict(zip(gen_header, gen_rows[index])) == dict(zip(ref_header, ref_rows[index]))


