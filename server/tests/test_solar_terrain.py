def flat_grid(rows, cols, elevation):
    return engine.TerrainGridInterpolator([elevation] * (rows * cols), rows, cols,
                                          0, cols - 1, 0, rows - 1, 1.0)


def north_peak_grid():
    elevations = [0.0] * (11 * 11)
    elevations[10 * 11 + 5] = 10.0
    return engine.TerrainGridInterpolator(elevations, 11, 11, 0, 10, 0, 10)


def by_azimuth(profile, az):
    return next(s.elevation_deg for s in profile if abs(s.azimuth_deg - az) < 1e-6)


