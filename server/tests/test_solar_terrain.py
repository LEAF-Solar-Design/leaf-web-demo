def test_the_horizon_demo_meets_its_closed_form():
    """LEAFHORIZONDEMO's own anchor: atan(5/100) at az 0, zero everywhere else."""
    peak_row, peak_col, peak_m = probes.HORIZON_PEAK
    grid = probes._grid(probes.HORIZON_GRID,
                        lambda r, c, x, y: peak_m if (r, c) == (peak_row, peak_col) else 0.0)
    profile = engine.generate_horizon_profile(grid, 0.0, 0.0, observer_height_m=0.0,
                                              azimuth_step_deg=10.0, ray_step_du=1.0)
    assert len(profile) == 36
    # The peak node sits exactly on the az-0 ray at s = 100, so the sample is
    # exact; the plugin's RadToDeg constant, not 180/pi applied twice, is the
    # multiplier (the two can differ in the last bit).
    assert profile[0].elevation_deg == math.atan2(5.0, 100.0) * engine.RAD_TO_DEG
    assert all(sample.elevation_deg == 0.0 for sample in profile[1:])


