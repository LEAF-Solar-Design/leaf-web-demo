def test_isotropic_horizontal_returns_ghi():
    ghi = 800.0 * math.cos(30.0 * math.pi / 180.0) + 200.0
    poa = iso(800.0, 200.0, ghi, 30.0, 180.0, 0.0, 180.0)
    assert poa.global_irradiance == pytest.approx(ghi, abs=NUMERIC)
    assert poa.sky_diffuse == pytest.approx(200.0, abs=NUMERIC)
    assert poa.ground_diffuse == pytest.approx(0.0, abs=NUMERIC)


def test_isotropic_vertical_sky_diffuse_is_half_dhi():
    assert iso(0, 400, 400, 45, 180, 90, 180).sky_diffuse == pytest.approx(200.0, abs=NUMERIC)


