def heat_grid(elevs):
    """BuildGrid: extents (0,0)-(cols-1, rows-1), metersPerUnit 1."""
    rows, cols = len(elevs), len(elevs[0])
    flat = [value for row in elevs for value in row]
    return engine.TerrainGridInterpolator(flat, rows, cols, 0, cols - 1, 0, rows - 1, 1.0)


def test_heatmap_2x2_grid_returns_four_cells():
    cells = engine.compute_cells(heat_grid([[100.0, 102.0], [98.0, 101.0]]), 100.0)
    assert len(cells) == 4


def test_heatmap_proposed_at_min_is_all_cut_or_neutral():
    cells = engine.compute_cells(heat_grid([[100.0, 110.0], [105.0, 108.0]]), 100.0)
    assert all(cell.delta_m >= 0.0 for cell in cells)


def test_heatmap_proposed_at_max_is_all_fill_or_neutral():
    cells = engine.compute_cells(heat_grid([[100.0, 110.0], [105.0, 108.0]]), 110.0)
