"""Studio's six terrain and irradiance engines against the licensed plugin, computed.

Two layers, all hermetic and none of them skipping:

  1. Every probe in the six licensed DEMO captures, reproduced by RUNNING
     Studio's fixtures through server/solar_terrain.py. The captures are the
     licensed AutoCAD 2025 run of 2026-09-23 and are COMMITTED at
     docs/parity/evidence/probes/demo-probes-20260923, so this layer reads the
     artifact itself rather than a transcription and every runner carries it.
     Each file is asserted whole, then probe by probe (one test per licensed
     row, collected from the committed file), so a failure names the row.
  2. The plugin's OWN unit tests for these engines, ported case for case from
     Tests/Tests/LeafHeatmapTests.cs, LeafHorizonProfileTests.cs,
     LeafInPlaneIrradianceTests.cs, LeafGradingPadTests.cs,
     LeafTerrainProfileTests.cs and LeafCapacityIterationTests.cs (read
     2026-09-23 at C:/tmp/solar-parity/wt-b25-s17). One case is omitted and
     named here rather than left as a silent gap:
     LeafGradingPadTests.CommandSource_RegistersInteractiveBuildAndPersistenceFlow
     greps the plugin's AutoCAD command source, which is not what this port
     covers. C# exception types map to Python ones: ArgumentNullException to
     TypeError, ArgumentException to ValueError, InvalidOperationException to
     solar_terrain.SiteOutsideTerrainError.

Line endings, and why the whole-file assertion normalizes them. The plugin
writes CRLF and this port writes CRLF, which
`test_the_generated_bytes_carry_the_plugins_encoding_and_crlf` asserts on the
GENERATED bytes. The committed capture is a tracked text file, so git's checkout
translation decides its on-disk line endings, and comparing against it byte for
byte would be asserting a git setting rather than a parity fact. The byte order
mark is not a line ending, so the whole-file assertion keeps it.

Nothing here feeds a captured value back into the port: solar_terrain.py
computes every number and renders every string, and these are the assertions it
must meet.
"""

from __future__ import annotations

