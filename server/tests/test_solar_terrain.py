def test_horizon_north_peak_matches_the_closed_form():
    profile = engine.generate_horizon_profile(north_peak_grid(), 5, 5, observer_height_m=0.0,
                                              azimuth_step_deg=1.0, ray_step_du=0.25)
    expected = math.atan2(10.0, 5.0) * 180.0 / math.pi
    assert by_azimuth(profile, 0) == pytest.approx(expected, abs=0.5)
    assert by_azimuth(profile, 180) == pytest.approx(0.0, abs=0.01)


