def test_horizon_east_west_ridge_is_symmetric():
    e = [0.0] * 121
    for r in range(11):
        e[r * 11 + 0] = 5.0
        e[r * 11 + 10] = 5.0
    grid = engine.TerrainGridInterpolator(e, 11, 11, 0, 10, 0, 10)
    profile = engine.generate_horizon_profile(grid, 5, 5, observer_height_m=0,
                                              azimuth_step_deg=1, ray_step_du=0.25)
    for az in (30.0, 60.0, 90.0, 120.0):
        assert by_azimuth(profile, az) == pytest.approx(by_azimuth(profile, 360.0 - az), abs=0.1)


def test_horizon_north_south_ridge_is_symmetric():
    e = [0.0] * 121
    for c in range(11):
        e[0 * 11 + c] = 5.0
        e[10 * 11 + c] = 5.0
    grid = engine.TerrainGridInterpolator(e, 11, 11, 0, 10, 0, 10)
    profile = engine.generate_horizon_profile(grid, 5, 5, observer_height_m=0,
                                              azimuth_step_deg=1, ray_step_du=0.25)
    for az in (30.0, 60.0, 120.0, 150.0):
        mirror = math.fmod((180.0 - az) + 360.0, 360.0)
        assert by_azimuth(profile, az) == pytest.approx(by_azimuth(profile, mirror), abs=0.1)


