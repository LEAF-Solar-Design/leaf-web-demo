def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


calcs = _load("solar_probe_calcs", ROOT / "server" / "solar_probe_calcs.py")
probes = _load("solar_probe_calcs_probes", ROOT / "scripts" / "solar_probe_calcs_probes.py")

# The licensed capture is committed in this repo, so every runner carries it.
DEFAULT_REFERENCE_DIR = ROOT / "docs/parity/evidence/probes/demo-probes-20260923"
REFERENCE_DIR = Path(os.environ.get("LEAF_SOLAR_W3_PROBE_CALCS_REF",
                                    str(DEFAULT_REFERENCE_DIR)))

ALL_FILES = tuple(name for demo in sorted(probes.DEMOS)
                  for name in probes.file_names(demo))
CROSS_AXIS_M = probes.SHADELIMIT_CROSS_AXIS_M


def reference_text(name):
    """The committed capture, with the checkout's line endings normalized."""
    return REFERENCE_DIR.joinpath(name).read_bytes().decode("utf-8").replace("\r\n", "\n")


def generated_text(name):
    """Studio's own rendering of one file, computed from its scenario list."""
    return probes.build(probes.FILE_DEMOS[name])[name]


def reference_rows(name):
    """The capture's CSV rows as dicts, header row giving the field names."""
    lines = [line for line in reference_text(name).split("\n")
             if line and not line.startswith("#")]
    header = lines[0].split(",")
    return [dict(zip(header, line.split(","))) for line in lines[1:]]


