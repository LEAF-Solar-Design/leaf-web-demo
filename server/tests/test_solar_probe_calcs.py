def test_max_gcr_for_sla_closed_form_reference_15deg_60tilt():
    """g = tan(SLA) / (sin(t) + tan(SLA) * cos(t)), a trig identity, not the impl."""
    tan_sla = math.tan(15.0 * math.pi / 180.0)
    expected = tan_sla / (math.sin(60.0 * math.pi / 180.0)
                          + tan_sla * math.cos(60.0 * math.pi / 180.0))
    assert calcs.max_gcr_for_sla(15.0, 60.0) == pytest.approx(expected, abs=1e-9)


