SHADELIMIT_ROWS = reference_rows("leafshadelimit_demo.csv")


@pytest.mark.parametrize("row", SHADELIMIT_ROWS,
                         ids=[row["label"] for row in SHADELIMIT_ROWS])
def test_shade_limit_reproduces_each_licensed_probe(row):
    """Each block recomputes its own columns from the row's inputs.

    Block A's GCR and target SLA and block C's timestamp are scenario INPUTS, so
    they come from Studio's own list, never from the capture: the file renders
    its gcr_in at twelve decimals, and re-running the forward formula on that
    ROUNDED value would answer 59.999999999950 where the plugin answers 60. The
    rendering of the input is asserted too, so nothing about it goes unchecked.
    Block B's target SLA is genuinely in the file, in the column the other two
    blocks use for an output.
    """
    tilt_deg = float(row["tilt_deg"])
    if row["block"] == "A":
        anchors = {name: (gcr, sla) for name, gcr, _, sla in probes.SHADELIMIT_ANCHORS}
        gcr, expected_sla = anchors[row["label"]]
        assert calcs.format_fixed(gcr, 12) == row["gcr_in"]
        assert calcs.format_fixed(
            calcs.compute_shade_limit_angle(gcr, tilt_deg), 12) == row["sla_target_deg"]
        max_gcr = calcs.max_gcr_for_sla(expected_sla, tilt_deg)
        assert calcs.format_fixed(max_gcr, 12) == row["max_gcr"]
        assert calcs.format_fixed(calcs.compute_shade_limit_angle(max_gcr, tilt_deg),
                                  12) == row["sla_reconstructed_deg"]
        assert calcs.format_fixed(
            calcs.min_pitch_for_sla(expected_sla, CROSS_AXIS_M, tilt_deg),
            9) == row["min_pitch_m"]
    elif row["block"] == "B":
        sla_target = float(row["sla_target_deg"])
        max_gcr = calcs.max_gcr_for_sla(sla_target, tilt_deg)
        assert calcs.format_fixed(max_gcr, 12) == row["max_gcr"]
        assert calcs.format_fixed(calcs.compute_shade_limit_angle(max_gcr, tilt_deg),
                                  12) == row["sla_reconstructed_deg"]
        assert calcs.format_fixed(
            calcs.min_pitch_for_sla(sla_target, CROSS_AXIS_M, tilt_deg),
            9) == row["min_pitch_m"]
    else:
        moment = dict(probes.SHADELIMIT_AUTOCALCS)[row["label"]]
        result = calcs.shade_limit_auto_calculate(
            probes.SHADELIMIT_LAT_DEG, probes.SHADELIMIT_LON_DEG, moment,
            CROSS_AXIS_M, probes.SHADELIMIT_MAX_TILT_DEG)
        assert calcs.format_fixed(result.sun_elevation_deg, 12) == row["sla_target_deg"]
        assert calcs.format_fixed(result.max_gcr, 12) == row["max_gcr"]
        assert calcs.format_fixed(result.min_pitch_m, 9) == row["min_pitch_m"]
        assert calcs.format_fixed(result.sun_elevation_deg, 6) == row["sun_elev_deg"]
        assert calcs.format_fixed(result.sun_azimuth_deg, 6) == row["sun_az_deg"]
        assert ("1" if result.is_daytime else "0") == row["is_daytime"]


