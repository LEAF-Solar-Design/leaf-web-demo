"""Studio's four probe calculations against the licensed plugin, computed.

Three layers, all hermetic and none of them skipping:

  1. The C# number formatters this port depends on that the NEC port did not
     already need: the "R" shortest round-trippable form, and the round-half-to
     EVEN rule `(int)Math.Round` uses inside BucketCoordinate, which is the
     opposite of the away-from-zero rule the "F<n>" form uses one file away.
  2. The plugin's OWN unit tests, ported case for case from
     Tests/Tests/PanelGroupTradeCalculatorTests.cs,
     Tests/Tests/LeafTorqueTubeShadeTests.cs, Tests/Tests/LeafShadeLimitTests.cs,
     Tests/Tests/LeafShadeLimitExternalReferenceTests.cs and
     Tests/Tests/ProjectSummaryReportTests.cs (read 2026-09-22 at
     C:/tmp/solar-parity/wt-b25-s17).
  3. Every probe in the four licensed DEMO captures, reproduced by RUNNING
     Studio's scenario lists through server/solar_probe_calcs.py. The captures
     are the licensed AutoCAD 2025 run of 2026-09-23 and are COMMITTED at
     docs/parity/evidence/probes/demo-probes-20260923, so this layer reads the
     artifact itself rather than a transcription and every runner carries it.
     Each file is asserted whole (the generated text equals the capture) and
     then probe by probe, so a failure names the scenario that moved.

Line endings, and why the whole-file assertion normalizes them. The plugin
writes CRLF and this port writes CRLF, which `test_generated_files_use_the
_plugins_crlf` asserts on the GENERATED bytes. The committed capture is a
tracked text file, so git's checkout translation (core.autocrlf on this host)
decides its on-disk line endings, and comparing against it byte for byte would
be asserting a git setting rather than a parity fact. So the capture comparison
normalizes CRLF to LF on both sides, and the CRLF contract is proven separately
where it is actually ours to hold.

Nothing here feeds a captured value back into the port: solar_probe_calcs.py
computes every number and renders every string, and these are the assertions it
must meet.
"""

