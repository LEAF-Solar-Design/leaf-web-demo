"""Offhost acceptance: private Postgres and an independently installed export.

This explicit proof is separate from the ordinary fast unit suite. Use the
allocated mini rootpytest runner; no shared database or deployment is touched.
"""
import importlib.util
import io
import json
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def test_project_page_database_and_independent_next_build(tmp_path):
    node, npm = shutil.which('node'), shutil.which('npm')
    assert node and npm, 'Node and npm are required for the independent source proof'
    database = subprocess.run([node, str(ROOT / 'scripts/prove_project_page_database.mjs'), sys.executable],
                              cwd=ROOT, capture_output=True, text=True, timeout=300)
    print(database.stdout[-14000:])
    assert database.returncode == 0, database.stderr[-6000:]
    spec = importlib.util.spec_from_file_location('page_template', ROOT / 'platform/web_page_template.py')
    template = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(template)
    document = {'label': 'Portable page proof', 'headline': 'Bakes made with care',
                'description': 'Independently installed and built.', 'status': 'Coming soon',
                'theme': 'cream', 'alignment': 'center'}
    archive = template.source_archive(document, 1)
    # This is generated by our closed template, with fixed relative members.
    with zipfile.ZipFile(io.BytesIO(archive)) as source:
        source.extractall(tmp_path)
    installed = subprocess.run([npm, 'install', '--ignore-scripts', '--no-audit', '--no-fund'],
                               cwd=tmp_path, capture_output=True, text=True, timeout=180)
    assert installed.returncode == 0, installed.stderr[-6000:]
    built = subprocess.run([npm, 'run', 'build'], cwd=tmp_path,
                          capture_output=True, text=True, timeout=240)
    print(built.stdout[-7000:])
    assert built.returncode == 0, built.stderr[-6000:]
    output = tmp_path / '.next/server/app/index.html'
    assert output.is_file(), 'Next did not emit the page HTML'
    html = output.read_text(encoding='utf-8')
    assert document['headline'] in html and document['description'] in html
    assert json.loads((tmp_path / 'page.json').read_text()) == document
    print('Portable Next source installed independently, built, and rendered the saved content.')
